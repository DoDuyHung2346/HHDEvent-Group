-- Persistent RAG data for production.
-- The FastAPI backend accesses these tables with a server-only PostgreSQL
-- connection. Browser clients never receive that connection string.

insert into storage.buckets (id, name, public)
values ('rag-documents', 'rag-documents', false)
on conflict (id) do update set public = false;

create table if not exists public.documents (
  doc_id text primary key,
  filename text not null,
  title text not null,
  doc_type text not null,
  version integer not null default 1,
  status text not null default 'queued',
  sha256 text not null,
  size_bytes integer not null default 0,
  storage_backend text not null default 'local',
  storage_path text,
  uploaded_at text not null,
  effective_date text,
  expires_date text,
  n_chunks integer not null default 0,
  warnings_json text not null default '[]',
  active integer not null default 1
);

create table if not exists public.chunks (
  chunk_id text primary key,
  doc_id text not null references public.documents(doc_id) on delete cascade,
  ordinal integer not null,
  parent_id text,
  breadcrumb text not null default '',
  text_display text not null,
  text_index text not null,
  tokens_vi text not null default '',
  content_hash text not null,
  doc_type text not null,
  category text,
  effective_date text,
  expires_date text,
  page integer,
  table_json text,
  questions_json text not null default '[]',
  keywords_json text not null default '[]',
  context_summary text,
  enriched integer not null default 0,
  active integer not null default 1
);

create table if not exists public.chunk_questions (
  qid text primary key,
  chunk_id text not null references public.chunks(chunk_id) on delete cascade,
  question text not null,
  embedding bytea
);

create table if not exists public.parents (
  parent_id text primary key,
  doc_id text not null references public.documents(doc_id) on delete cascade,
  text text not null
);

create table if not exists public.ingest_jobs (
  job_id text primary key,
  doc_id text not null,
  filename text not null,
  status text not null default 'queued',
  stage text not null default 'validate',
  progress double precision not null default 0,
  error text,
  warnings_json text not null default '[]',
  chunks_total integer not null default 0,
  chunks_embedded integer not null default 0,
  chunks_indexed integer not null default 0,
  created_at text not null,
  finished_at text
);

create table if not exists public.kb_meta (
  key text primary key,
  value text not null
);

create table if not exists public.traces (
  trace_id text primary key,
  ts text not null,
  session_id text not null,
  query text not null,
  standalone_query text,
  intent text,
  status text not null,
  cache text not null default 'none',
  kb_version text not null default '',
  retrieved_json text not null default '[]',
  gate_json text not null default '{}',
  answer text,
  citations_json text not null default '[]',
  followups_json text not null default '[]',
  latency_json text not null default '{}',
  tokens_json text not null default '{}',
  cost_usd double precision not null default 0,
  error text
);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  trace_id text not null,
  rating integer not null,
  comment text,
  ts text not null
);

create table if not exists public.kb_gaps (
  id bigint generated by default as identity primary key,
  query_norm text not null unique,
  first_seen text not null,
  last_seen text not null,
  count integer not null default 1,
  last_trace_id text,
  resolved integer not null default 0
);

create index if not exists documents_active_uploaded_idx on public.documents (active, uploaded_at desc);
create index if not exists chunks_active_doc_idx on public.chunks (active, doc_id);
create index if not exists chunks_active_type_idx on public.chunks (active, doc_type);
create index if not exists ingest_jobs_doc_idx on public.ingest_jobs (doc_id);
create index if not exists traces_session_ts_idx on public.traces (session_id, ts desc);

-- Safe if a previous local-to-cloud rollout created these tables without file
-- metadata. `if not exists` makes this migration repeatable.
alter table public.documents add column if not exists storage_backend text not null default 'local';
alter table public.documents add column if not exists storage_path text;

alter table public.documents enable row level security;
alter table public.chunks enable row level security;
alter table public.chunk_questions enable row level security;
alter table public.parents enable row level security;
alter table public.ingest_jobs enable row level security;
alter table public.kb_meta enable row level security;
alter table public.traces enable row level security;
alter table public.feedback enable row level security;
alter table public.kb_gaps enable row level security;

-- No anon/authenticated policies: only the server-side PostgreSQL connection
-- and Supabase service role can operate on RAG data.
